% W7X_GRF  Green's identity on the W7-X plasma boundary.
%
% Run it:  w7x_grf
%
% Meshes W7-X through stellarator_geo_mex, plots the mesh, then runs the same
% GRF check stellarator_grf.m does: an analytic interior harmonic gives u and
% du/dn on the boundary, the FMM evaluates SLP(du/dn) - DLP(u) at every node,
% and each close panel replaces its own contribution with the rrq correction.
% For an interior solution the identity returns u, so what is printed is the
% relative error of that.  The density is harmonic in R^3, so it works on this
% surface as it does on the test torus.
%
% Needs, beyond the geometry mex:
%   make mex                     in the package root, for qol_rrq_mex
%   the surfquadr kernels        Lap3dSLPfmm, Lap3dDLPfmm, Lap3dSLPmat, Lap3dDLPmat
%   FMM3D's MATLAB interface
%
% The mesh is built by the C, called through the adaptive form of the gateway:
%
%   [sx,snx,sw,rts,rps,ntri] = stellarator_geo_mex(mp,np,order, ...
%                                x0,w0,D,uvs,wts, surf, restol, cap)
%
% surf is 4-by-nmode, rows m; n; Rmn; Zmn, in the VMEC convention
%
%     R(theta,phi) = sum Rmn cos(m*theta - n*nfp*phi)
%     Z(theta,phi) = sum Zmn sin(m*theta - n*nfp*phi)
%     x = R cos(phi),  y = R sin(phi),  z = Z
%
% and restol drives the refinement the C does on top of the aspect split:
% split a panel while the last two degrees of the Legendre expansion of its
% mean curvature carry more than restol of the whole spectrum, then 2:1
% balance so no two face neighbours differ by more than one level.
% restol <= 0 reproduces the old single-pass aspect-only mesh.
%
% Output is Vioreanu-Rokhlin triangles, hdim = order*(order+1)/2 nodes each,
% two per chart, laid out consecutively -- the same arrays stellarator_grf.m
% slices into pan{k}.
%
% Build the mex first:
%   mex -R2018a ../utils/stellarator_geo_mex.c
%
% Coefficients are the W7-X standard (EIM) configuration, nfp = 5, 288 modes,
% from hiddenSymmetries/simsopt, tests/test_files/input.W7-X_standard_configuration
% -- extracted by Matt Landreman (2019-10-08) from a free-boundary run in
% Geiger's W7-X VMEC database, config 1000_1000_1000_1000_+0000_+0000/01/00jh_l,
% beta = 0, current = 0.

% mp     = 12;        % poloidal panels
% np     = 36;        % toroidal panels
% order  = 8;         % Vioreanu-Rokhlin order
% restol = 1e-2;      % curvature refinement tolerance; <= 0 for aspect only

% 5.5315e-06
mp     = 24;        % poloidal panels
np     = 72;        % toroidal panels
order  = 8;         % Vioreanu-Rokhlin order
restol = 1e-4;      % curvature refinement tolerance; <= 0 for aspect only

% % 2.9286e-07
% mp     = 36;        % poloidal panels
% np     = 108;        % toroidal panels
% order  = 8;         % Vioreanu-Rokhlin order
% restol = 1e-6;      % curvature refinement tolerance; <= 0 for aspect only

% %
% mp     = 48;        % poloidal panels
% np     = 144;        % toroidal panels
% order  = 8;         % Vioreanu-Rokhlin order
% restol = 1e-6;      % curvature refinement tolerance; <= 0 for aspect only

cap    = 1000000;    % chart-list capacity handed to the C
fmmeps = 1e-11;     % FMM tolerance for the far field
doplot = 1;

[xg, wg, Dg] = gauss(order);
[uvs, wts]   = get_vioreanu_nodes(order-1);
D4 = w7x_modes();

nfp = 5; nmode = size(D4,2); mn = D4(1:2,:); rc = D4(3,:).'; zs = D4(4,:).';
charts = zeros(6,cap);
[charts,nchart,ntri,geometry_ier] = lqsm_stellarator_mesh_init_mex( ...
    mp,np,order,nfp,nmode,mn,rc,zs,restol,cap,charts,0,0,0);
assert(geometry_ier == 0, 'W7-X mesh init failed');
hdim = order*(order+1)/2;
nsrc = ntri*hdim;
[sx,snx,sw,rts,rps,geometry_ier] = lqsm_create_stellarator_tri_mesh_mex( ...
    mp,np,order,nfp,nmode,mn,rc,zs,nchart,charts(:,1:nchart),ntri, ...
    zeros(3,nsrc),zeros(3,nsrc),zeros(nsrc,1),zeros(3,nsrc), ...
    zeros(3,nsrc),0);
assert(geometry_ier == 0, 'W7-X mesh build failed');
s.x = sx;  s.nx = snx;  s.w = sw;
vol = sum(sum(sx.*snx,1).*sw)/3;
fprintf('W7-X: %d triangles, %d nodes (mp %d, np %d, order %d, restol %.0e)\n', ...
        ntri, size(sx,2), mp, np, order, restol);
fprintf('  area %.9f   volume %.9f\n', sum(sw), vol);
fprintf('  R [%.4f %.4f]   Z [%.4f %.4f]\n', ...
        min(hypot(sx(1,:),sx(2,:))), max(hypot(sx(1,:),sx(2,:))), ...
        min(sx(3,:)), max(sx(3,:)));

% ---- plot ----
% One triangulation of the reference-triangle nodes serves every panel: the
% same (u,v) connectivity shifted by each panel's node offset.  Panel outlines
% are the boundary edges of that same reference triangulation.
conn = delaunay(uvs(1,:).', uvs(2,:).');
be   = freeBoundary(triangulation(conn, uvs(1,:).', uvs(2,:).'));

nf = size(conn,1);
F  = reshape(permute(repmat(conn, [1 1 ntri]), [1 3 2]), [], 3) ...
     + repmat(kron((0:ntri-1).'*hdim, ones(nf,1)), 1, 3);

ne = size(be,1);
i1 = reshape(repmat(be(:,1).', ntri, 1).' + repmat((0:ntri-1)*hdim, ne, 1), [], 1);
i2 = reshape(repmat(be(:,2).', ntri, 1).' + repmat((0:ntri-1)*hdim, ne, 1), [], 1);
E  = [sx(:,i1); sx(:,i2); nan(3, numel(i1))];
E  = reshape(E, 3, []);

if doplot
figure
patch('Vertices', sx.', 'Faces', F, 'FaceColor', [0.45 0.62 0.80], ...
      'EdgeColor', 'none', 'FaceLighting', 'gouraud');
hold on
plot3(E(1,:), E(2,:), E(3,:), 'k-', 'LineWidth', 0.25);
axis equal off; view(-35, 25); camlight headlight; material dull
title(sprintf('W7-X: %d triangles, order %d, restol %.0e', ntri, order, restol));
hold off
end

% ---- GRF ----------------------------------------------------------------
[f, gradf] = torus_surf_den();
ub  = f(sx).';                          % boundary values of the interior soln
ubn = sum(snx.*gradf(sx), 1).';         % its normal derivative
t.x = sx;  t.nx = snx;

tic;
u = Lap3dSLPfmm(t, s, ubn, fmmeps) - Lap3dDLPfmm(t, s, ub, fmmeps);
fmmtime = toc;

nquad   = order + 2;
orderff = order + 2;
distff  = 1.4;
exterior = true;
isimd   = 0;
ichart  = 0;            % the adaptive chart list is not exposed to uv2x yet;
                        % measured identical to ichart = 1 from order 8 up
sbdnp   = 3;
nbd     = sbdnp*nquad;
xbuf    = zeros(3, nbd+3);
[tgl,wgl,Dgl,w_bclag,Legmat,umatr,vmatr] = ...
    qol_simplex_precomp_mex(nquad,order-1,hdim);
nsrc    = size(sx, 2);
allidx  = 1:nsrc;

tic;
for k = 1:ntri
  js   = (k-1)*hdim + (1:hdim);
  sk.x = sx(:,js);  sk.nx = snx(:,js);  sk.w = sw(js);
  sxk  = sk.x;  snxk = sk.nx;  swk = sk.w;
  rtsk = rts(:,js);  rpsk = rps(:,js);

  qradii = 1.75*sqrt(sum(swk));
  qpoint = mean(sxk, 2);
  near   = sum((sx - qpoint).^2, 1) < qradii^2;
  idxs   = allidx(near);
  m      = numel(idxs);
  if m == 0, continue; end
  tc.x   = sx(:,idxs);

  S_ij = zeros(m, hdim);  K_ij = zeros(m, hdim);
  Om   = zeros(4*hdim, m);  Ias = zeros(m, 1);  timeinfo = zeros(20, 1);
  [S_ij,K_ij,~,~,timeinfo] = qol_rrq_mex(m,tc.x,hdim,sxk,snxk,swk, ...
        rtsk,rpsk,order,nquad,orderff,distff,exterior,isimd, ...
        ichart, xbuf(:,1:nbd), xbuf(:,nbd+1:nbd+3), ...
        tgl,wgl,Dgl,w_bclag,Legmat,umatr,vmatr, ...
        S_ij, K_ij, Om, Ias, timeinfo);

  % naive block, with the self entries zeroed the way the FMM drops them
  Sn = Lap3dSLPmat(tc, sk);
  Kn = Lap3dDLPmat(tc, sk);
  [~, col] = ismember(idxs, js);
  hit = col > 0;
  if any(hit)
    selfIdx = find(hit) + (col(hit) - 1)*m;
    Sn(selfIdx) = 0;
    Kn(selfIdx) = 0;
  end

  u(idxs) = u(idxs) + ((S_ij - Sn)*ubn(js) - (K_ij - Kn)*ub(js));
end
closetime = toc;

err = max(abs(u))/max(abs(ubn));
fprintf('GRF max rel err %.4e   (fmm %.2f s, close %.2f s)\n', err, fmmtime, closetime);

keyboard

epts = abs(u)/max(abs(ubn));
figure
scatter3(sx(1,:), sx(2,:), sx(3,:), 6, log10(max(epts, realmin)), 'filled');
axis equal off; colormap(jet); colorbar
clim([-12 -4]);
view(-35, 25);
title('W7-X GRF: log_{10} pointwise relative error');

% ======================================================================

function [f, gradf] = torus_surf_den()
% Interior Laplace solution: columns in R^3 to values (row vector), and grad f.
lam   = 0.5;
f     = @(x) exp(lam*x(1,:)).*cos(lam*x(2,:));
gradf = @(x) [lam*f(x); -lam*exp(lam*x(1,:)).*sin(lam*x(2,:)); 0*f(x)];
end

